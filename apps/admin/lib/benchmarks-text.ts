export type BenchKey = Key;
/** Looks a text up; `{name}` placeholders are replaced. An unknown key returns the key (visible in review, never a crash). */
export function bt(locale: Locale, key: BenchKey, params: Record<string, string> = {}): string {
  const text = (locale === 'ar' ? AR : EN)[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k: string) => params[k] ?? `{${k}}`);
}
