export const EXTRA_TEXTS: Record<Locale, Record<ExtraBenchKey, string>> = {
  en: EXTRA_EN,
  ar: EXTRA_AR,
};
export type BenchKey = BaseBenchKey | ExtraBenchKey;
const isExtra = (key: BenchKey): key is ExtraBenchKey => key in EXTRA_EN;

/** Looks a text up; `{name}` placeholders are replaced. */
export function bt(locale: Locale, key: BenchKey, params: Record<string, string> = {}): string {
  if (isExtra(key))
    return EXTRA_TEXTS[locale][key].replace(/\{(\w+)\}/g, (m, name: string) =>
      name in params ? String(params[name]) : m,
    );
  return t(locale, `bench.${key}` as MessageKey, params);
}
