import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { PINNED_TOOLCHAIN } from './toolchain';
import { PUB_ALLOWLIST } from '../policy/pub-policy';
import type { FieldSpec, MobileSpec, Permission, ScreenSpec } from './spec';

/** Static part of the template set: apps/api/templates/flutter-core (the same relative path from `src/` and from the compiled `dist/`). */
const TEMPLATE_DIR = join(__dirname, '../../../../../templates/flutter-core');
const PLACEHOLDER = 'APP_PACKAGE';

function walk(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}
let cache: Record<string, string> | null = null;
/** the static template files, path -> text (read once) */
export function staticTemplateFiles(): Record<string, string> {
  if (cache) return cache;
  const out: Record<string, string> = {};
  for (const f of walk(TEMPLATE_DIR)) out[relative(TEMPLATE_DIR, f).split('\\').join('/')] = readFileSync(f, 'utf8');
  return (cache = out);
}

/** Dart single-quoted string literal: every character that is syntax in Dart (`\`, `$`, `'`, line breaks) is escaped, so spec text can never become code. */
export const dartString = (s: string): string =>
  `'${s
    .replace(/\\/g, '\\\\')
    .replace(/\$/g, '\\$')
    .replace(/'/g, "\\'")
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n')
    .replace(/\t/g, '\\t')}'`;
const L = (b: { ar: string; en: string }) => `L(${dartString(b.ar)}, ${dartString(b.en)})`;
const color = (hex: string) => `Color(0xFF${hex.slice(1).toUpperCase()})`;
const FIELD_ENUM: Record<FieldSpec['type'], string> = {
  text: 'text',
  email: 'email',
  phone: 'phone',
  number: 'number',
  password: 'password',
  multiline: 'multiline',
  choice: 'choice',
  switch: 'toggle',
};
const field = (f: FieldSpec) =>
  `    FieldDef(id: ${dartString(f.id)}, label: ${L(f.label)}, type: FieldType.${FIELD_ENUM[f.type]}${f.required ? ', required: true' : ''}${
    f.options?.length
      ? `, options: [${f.options.map((o) => `OptionDef(${dartString(o.value)}, ${L(o.label)})`).join(', ')}]`
      : ''
  }),`;
const screen = (s: ScreenSpec) =>
  [
    `  ScreenDef(`,
    `    id: ${dartString(s.id)},`,
    `    title: ${L(s.title)},`,
    `    kind: ScreenKind.${s.kind},`,
    ...(s.body ? [`    body: ${L(s.body)},`] : []),
    ...(s.fields?.length ? [`    fields: [`, ...s.fields.map(field), `    ],`] : []),
    ...(s.items?.length
      ? [
          `    items: [`,
          ...s.items.map((i) => `      ItemDef(${L(i.title)}${i.subtitle ? `, ${L(i.subtitle)}` : ''}),`),
          `    ],`,
        ]
      : []),
    `  ),`,
  ].join('\n');

/** The Dart package name = the last segment of the application id (validated lower-case snake case by the spec). */
export const packageNameOf = (spec: MobileSpec): string => spec.app.packageId.split('.').pop()!;
/** the permissions the app declares: `internet` always (login and the API client need it) plus the spec's */
export const declaredPermissions = (spec: MobileSpec): Permission[] => [
  'internet',
  ...spec.permissions.filter((p) => p !== 'internet'),
];

function pubspec(spec: MobileSpec): string {
  const dep = (name: string) => {
    const e = PUB_ALLOWLIST[name]!;
    return e.constraint.startsWith('sdk:')
      ? `  ${name}:\n    ${e.constraint}`
      : `  ${name}: ${e.constraint}`;
  };
  const direct = Object.entries(PUB_ALLOWLIST).filter(([, e]) => e.kind === 'dependency').map(([n]) => n);
  const dev = Object.entries(PUB_ALLOWLIST).filter(([, e]) => e.kind === 'dev').map(([n]) => n);
  return [
    `name: ${packageNameOf(spec)}`,
    `description: ${JSON.stringify(spec.app.name.en)}`,
    `publish_to: 'none'`,
    `version: 1.0.0+1`,
    ``,
    `environment:`,
    `  sdk: "${PINNED_TOOLCHAIN.sdkConstraint}"`,
    ``,
    `dependencies:`,
    `  flutter:`,
    `    sdk: flutter`,
    ...direct.map(dep),
    ``,
    `dev_dependencies:`,
    `  flutter_test:`,
    `    sdk: flutter`,
    ...dev.map(dep),
    ``,
    `flutter:`,
    `  uses-material-design: true`,
    ``,
  ].join('\n');
}

function appSpecDart(spec: MobileSpec): string {
  return [
    `// GENERATED by the ${PINNED_TOOLCHAIN.templateSet} template set from the approved mobile spec. Do not edit: regenerate from the spec.`,
    `import 'package:flutter/material.dart';`,
    ``,
    `import '../core/models.dart';`,
    ``,
    `const L kAppName = ${L(spec.app.name)};`,
    `const Color kPrimary = ${color(spec.theme.primary)};`,
    `// ignore: unnecessary_nullable_for_final_variable_declarations`,
    `const Color? kSecondary = ${spec.theme.secondary ? color(spec.theme.secondary) : 'null'};`,
    `const bool kSupportsDark = ${spec.theme.dark};`,
    `const String kDefaultLocale = ${dartString(spec.defaultLocale)};`,
    `const bool kAuthEnabled = ${spec.auth.enabled};`,
    `const String kInitialRoute = ${dartString('/' + spec.navigation.initial)};`,
    `const List<String> kTabs = [${spec.navigation.tabs.map(dartString).join(', ')}];`,
    ``,
    `const List<ScreenDef> kScreens = [`,
    ...spec.screens.map(screen),
    `];`,
    ``,
  ].join('\n');
}

function readme(spec: MobileSpec): string {
  return [
    `# ${spec.app.name.en}`,
    ``,
    `Flutter project generated by Nuzm (${PINNED_TOOLCHAIN.templateSet}). Pinned toolchain: Flutter ${PINNED_TOOLCHAIN.flutter}, Dart ${PINNED_TOOLCHAIN.dart}.`,
    ``,
    `The platform folders (\`android/\`, \`ios/\`) are not stored in the project: create them once with the pinned toolchain:`,
    ``,
    '```',
    `flutter create --platforms=android,ios --org ${spec.app.packageId.split('.').slice(0, -1).join('.')} --project-name ${packageNameOf(spec)} .`,
    `flutter pub get`,
    `flutter analyze && flutter test`,
    `flutter run --dart-define=API_BASE_URL=https://your-api.example`,
    '```',
    ``,
    `Declared permissions (see \`tool/nuzm-mobile.json\`): ${declaredPermissions(spec).join(', ')}.`,
    ``,
    `A web preview is a convenience, not a guarantee of how the app looks or behaves on a device; test on real devices before any release.`,
    ``,
  ].join('\n');
}

/** Every file of the generated project (path -> text): the static template set with the package name substituted, plus the spec-derived files. Deterministic. */
export function generateFlutterProject(spec: MobileSpec): Record<string, string> {
  const pkg = packageNameOf(spec);
  const files: Record<string, string> = {};
  for (const [path, text] of Object.entries(staticTemplateFiles())) files[path] = text.split(PLACEHOLDER).join(pkg);
  files['pubspec.yaml'] = pubspec(spec);
  files['lib/generated/app_spec.dart'] = appSpecDart(spec);
  files['README.md'] = readme(spec);
  files['tool/nuzm-mobile.json'] =
    JSON.stringify(
      {
        templateSet: PINNED_TOOLCHAIN.templateSet,
        flutter: PINNED_TOOLCHAIN.flutter,
        dart: PINNED_TOOLCHAIN.dart,
        applicationId: spec.app.packageId,
        packageName: pkg,
        appName: spec.app.name,
        permissions: declaredPermissions(spec),
      },
      null,
      2,
    ) + '\n';
  return Object.fromEntries(Object.entries(files).sort(([a], [b]) => (a < b ? -1 : 1)));
}
