describe('the web-app workspace: history in the chat and links into the panels', () => {
  const session = {
    id: 's1',
    title: 't',
    projectId: 'p1',
    state: 'open',
    dataRegion: 'sa',
    createdAt: '',
  };
  const project = {
    id: 'p1',
    name: 'Clinic app',
    dataRegion: 'sa-central',
    headVersionId: 'v2',
    headSeq: 2,
    lastDeployment: null,
  };
  const old = run({
    id: 'r0',
    state: 'failed',
    artifacts: [],
    error: { code: 'run_failed', details: ['The spec names two entities "Patient".'] },
    createdAt: '2026-11-19T08:00:10Z',
  });
  const messages = [
    {
      id: 'm1',
      sessionId: 's1',
      runId: null,
      role: 'user' as const,
      content: 'first brief',
      createdAt: '2026-11-19T08:00:00Z',
    },
    {
      id: 'm2',
      sessionId: 's1',
      runId: null,
      role: 'user' as const,
      content: 'second brief',
      createdAt: '2026-11-20T09:00:00Z',
    },
  ];
  const ws = (over: Partial<Parameters<typeof WebAppWorkspace>[0]> = {}) =>
    render(
      <WebAppWorkspace
        locale="en"
        initial={project}
        session={session}
        messages={messages}
        initialRun={run({ state: 'succeeded' })}
        allowedTabs={[...APP_TABS]}
        mfaFactorId={null}
        can={CAN}
        {...over}
      />,
    );
  const withRuns = () =>
    route((url) => {
      if (url.startsWith('/v1/ai/runs?'))
        return json(200, { items: [run(), old], nextCursor: null });
      return null;
    });

  it('keeps an earlier build in the conversation after the request that started it, with its failure reasons', async () => {
    withRuns();
    streams.r1 = { run: run(), events: BUILD_EVENTS };
    streams.r0 = { run: old, events: [ev('created'), ev('node_failed', { node: 'architecture' })] };
    const { container } = ws();
    await waitFor(() => expect(container.querySelector('.wsp-past')).toBeTruthy());
    const past = container.querySelector('.wsp-past') as HTMLElement;
    // right after its request, before the second one
    const order = [...container.querySelectorAll('.bld-list > li')].map((li) =>
      li.classList.contains('bld-hist') ? 'run' : 'msg',
    );
    expect(order).toEqual(['msg', 'run', 'msg']);
    expect(within(past).getByText('The spec names two entities "Patient".')).toBeTruthy();
    // its events are read only when it is opened
    expect(within(past).queryByRole('list', { name: t('en', 'wsp.ev.title') })).toBeNull();
    fireEvent.click(within(past).getByRole('button', { name: t('en', 'wsp.hist.show') }));
    expect(await within(past).findByRole('list', { name: t('en', 'wsp.ev.title') })).toBeTruthy();
    expect(within(past).getByText('Architecture and app spec: failed')).toBeTruthy();
  });

  it('without access to runs the chat shows the current run only', async () => {
    route((url) => (url.startsWith('/v1/ai/runs?') ? json(403, {}) : null));
    streams.r1 = { run: run(), events: BUILD_EVENTS };
    const { container } = ws();
    await waitFor(() => expect(calls.some((u) => u.startsWith('/v1/ai/runs?'))).toBe(true));
    expect(container.querySelector('.wsp-past')).toBeNull();
    expect(container.querySelector('.mws-run')).toBeTruthy();
  });

  it('a file link in the chat opens the Code tab, and a table link opens the Data tab on that view', async () => {
    api();
    streams.r1 = { run: run(), events: BUILD_EVENTS };
    const { container } = ws();
    // the timeline of this short build is open: follow "Open Code" of the files written
    fireEvent.click(await screen.findByRole('button', { name: t('en', 'wsp.open.code') }));
    await waitFor(() => expect(container.querySelector('[data-pane="code"]')).toBeTruthy());
    expect(location.search).toContain('tab=code');
    // "what was produced" → Migrations opens the Data tab on its migrations view
    fireEvent.click(await screen.findByRole('button', { name: /^Migrations/ }));
    await waitFor(() => expect(container.querySelector('[data-pane="data"]')).toBeTruthy());
    expect(location.search).toContain('tab=design');
    await waitFor(() =>
      expect(
        screen
          .getByRole('tab', { name: t('en', 'wsp.data.view.migrations') })
          .getAttribute('aria-selected'),
      ).toBe('true'),
    );
  });
});
