/** the project API as the panels read it */
const api = (opts: { migrations?: boolean; built?: boolean; head?: boolean } = {}) =>
  route((url) => {
    const u = new URL(url, 'http://x');
    if (u.pathname === '/v1/builder/projects/p1/files/content') {
      const path = u.searchParams.get('path')!;
      return CONTENT[path] === undefined
        ? json(404, {})
        : json(200, {
            path,
            mime: 'text/plain',
            size: CONTENT[path]!.length,
            encoding: 'utf8',
            content: CONTENT[path],
          });
    }
    if (u.pathname === '/v1/builder/projects/p1/files') {
      const files = u.searchParams.get('versionId') === 'v1' ? FILES_V1 : FILES_V2;
      return json(200, {
        versionId: u.searchParams.get('versionId'),
        items: opts.migrations === false ? files.filter((f) => !f.path.startsWith('db/')) : files,
      });
    }
    if (u.pathname === '/v1/builder/projects/p1/versions') return json(200, VERSIONS);
    if (u.pathname === '/v1/ai/runs')
      return json(200, { items: opts.built === false ? [] : [run()], nextCursor: null });
    const art = /^\/v1\/ai\/runs\/r1\/artifacts\/(a\d)$/.exec(u.pathname);
    if (art) return json(200, { payload: PAYLOAD[art[1]!] ?? null });
    if (u.pathname.endsWith('/forms') || u.pathname.endsWith('/cms-collections'))
      return json(200, { items: [] });
    if (u.pathname.endsWith('/sandboxes')) return json(200, { items: [] });
    if (u.pathname === '/v1/deployments') return json(200, { items: [], nextCursor: null });
    return null;
  });

