import { describe, expect, it } from 'vitest';
import type { RoleView, SpecView } from './appworkspace';
import {
  constraintText,
  endpointsOf,
  looksDestructive,
  migrationFiles,
  parseTables,
  tableModels,
} from './webapp-data';

const UP1 = `-- generated by the Nuzm app builder; do not edit by hand
CREATE TABLE "doctors" (
  "id" uuid PRIMARY KEY,
  "full_name" varchar(255) NOT NULL,
  "specialty" text NOT NULL CHECK ("specialty" IN ('general', 'dental')),
  "created_at" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "doctors_full_name_key" UNIQUE ("full_name")
);
CREATE TABLE "patients" (
  "id" uuid PRIMARY KEY,
  "full_name" varchar(255) NOT NULL,
  "balance" numeric(18,4),
  "doctor" uuid
);
ALTER TABLE "patients" ADD CONSTRAINT "patients_doctor_fkey" FOREIGN KEY ("doctor") REFERENCES "doctors"("id") ON DELETE SET NULL;
CREATE INDEX "patients_doctor_idx" ON "patients" ("doctor");`;
const UP2 = `ALTER TABLE "patients" ADD COLUMN "national_id" varchar(20);
ALTER TABLE "patients" DROP COLUMN "balance";`;

describe('parseTables: the generated SQL as tables', () => {
  const tables = parseTables([UP1, UP2]);
  it('reads the columns with their types, nullability, keys and defaults', () => {
    const doctors = tables.find((t) => t.name === 'doctors')!;
    expect(doctors.columns.map((c) => c.name)).toEqual([
      'id',
      'full_name',
      'specialty',
      'created_at',
    ]);
    const id = doctors.columns[0]!;
    expect(id).toMatchObject({ type: 'uuid', primary: true, notNull: true });
    expect(doctors.columns[1]).toMatchObject({ type: 'varchar(255)', notNull: true, unique: true });
    expect(doctors.columns[2]!.check).toContain('IN');
    expect(doctors.columns[3]).toMatchObject({ type: 'timestamptz', default: 'now()' });
  });
  it('keeps a type with a comma in its parentheses whole', () => {
    expect(
      tables.find((t) => t.name === 'patients')!.columns.some((c) => c.name === 'balance'),
    ).toBe(
      false, // dropped by the second migration
    );
    expect(parseTables([UP1])[1]!.columns.find((c) => c.name === 'balance')!.type).toBe(
      'numeric(18,4)',
    );
  });
  it('applies later migrations in order: a column added, a column dropped', () => {
    const cols = tables.find((t) => t.name === 'patients')!.columns.map((c) => c.name);
    expect(cols).toContain('national_id');
    expect(cols).not.toContain('balance');
  });
  it('reads foreign keys added by ALTER TABLE and indexes', () => {
    const p = tables.find((t) => t.name === 'patients')!;
    expect(p.columns.find((c) => c.name === 'doctor')!.references).toEqual({
      table: 'doctors',
      column: 'id',
      onDelete: 'SET NULL',
    });
    expect(p.indexes).toEqual(['patients_doctor_idx']);
  });
  it('a dropped table is gone and nothing is invented for text it cannot read', () => {
    expect(parseTables([UP1, 'DROP TABLE IF EXISTS "patients";']).map((t) => t.name)).toEqual([
      'doctors',
    ]);
    expect(parseTables(['SELECT 1;', 'CREATE TABLE broken ('])).toEqual([]);
  });
  it('ignores comments and strings that look like statements', () => {
    const sql = `-- CREATE TABLE "ghost" ("id" uuid);\n/* CREATE TABLE "ghost2" ("id" uuid); */\nCREATE TABLE "t" ("a" text DEFAULT 'CREATE TABLE x (y int)');`;
    expect(parseTables([sql]).map((t) => t.name)).toEqual(['t']);
  });
  it('tells the constraints of a column in a short list', () => {
    const c = parseTables([UP1])[0]!.columns;
    expect(constraintText(c[0]!)).toEqual(['PRIMARY KEY']);
    expect(constraintText(c[1]!)).toEqual(['NOT NULL', 'UNIQUE']);
    expect(constraintText(c[3]!)).toEqual(['NOT NULL', 'DEFAULT now()']);
  });
});

describe('migrationFiles', () => {
  it('pairs apply and reverse files and sorts them by version', () => {
    const out = migrationFiles([
      'db/migrations/0002_add_x.down.sql',
      'db/migrations/0001_init.sql',
      'db/migrations/0002_add_x.sql',
      'db/migrations/0001_init.down.sql',
      'src/app.ts',
      'db/migrations/readme.md',
      'db/migrations/../evil.sql',
    ]);
    expect(out).toEqual([
      {
        version: 1,
        name: 'init',
        upPath: 'db/migrations/0001_init.sql',
        downPath: 'db/migrations/0001_init.down.sql',
      },
      {
        version: 2,
        name: 'add_x',
        upPath: 'db/migrations/0002_add_x.sql',
        downPath: 'db/migrations/0002_add_x.down.sql',
      },
    ]);
  });
  it('a migration without a reverse file has no down path', () => {
    expect(migrationFiles(['db/migrations/0003_only_up.sql'])[0]!.downPath).toBeNull();
  });
});

const spec = {
  entities: [
    {
      name: 'Doctor',
      plural: 'doctors',
      label: { ar: 'طبيب', en: 'Doctor' },
      ownership: 'org',
      audit: false,
      stageField: null,
      fields: [
        {
          name: 'fullName',
          type: 'string',
          label: { ar: 'الاسم', en: 'Name' },
          required: true,
          unique: true,
          pii: true,
          references: null,
          enumValues: [],
        },
      ],
    },
    {
      name: 'Patient',
      plural: 'patients',
      label: { ar: 'مريض', en: 'Patient' },
      ownership: 'team',
      audit: true,
      stageField: null,
      fields: [
        {
          name: 'fullName',
          type: 'string',
          label: { ar: 'الاسم', en: 'Name' },
          required: true,
          unique: false,
          pii: true,
          references: null,
          enumValues: [],
        },
        {
          name: 'doctor',
          type: 'reference',
          label: { ar: 'الطبيب', en: 'Doctor' },
          required: false,
          unique: false,
          pii: false,
          references: 'Doctor',
          enumValues: [],
        },
      ],
    },
  ],
  roles: [],
  pages: [],
  api: { basePath: '/api/v1', defaultLimit: 25, maxLimit: 100 },
} as unknown as SpecView;
const roles: RoleView[] = [
  {
    name: 'reception',
    label: { ar: '', en: '' },
    scope: 'team',
    admin: false,
    permissions: { Patient: ['read', 'create'] },
  },
  {
    name: 'nurse',
    label: { ar: '', en: '' },
    scope: 'own',
    admin: false,
    permissions: { Doctor: ['read'] },
  },
];
const endpoints = [
  { method: 'GET', path: '/api/v1/patients', summary: 'List' },
  { method: 'GET', path: '/api/v1/patients/{id}', summary: 'Read' },
  { method: 'GET', path: '/api/v1/patients-archive', summary: 'not this table' },
  { method: 'GET', path: '/api/v1/doctors', summary: 'List' },
  { method: 'GET', path: '/health', summary: 'Health' },
];

describe('tableModels: the database joined with the spec, the API and the roles', () => {
  const models = tableModels(parseTables([UP1]), spec, endpoints, roles);
  const patients = models.find((m) => m.name === 'patients')!;
  it('labels the columns from the spec and marks the ones the platform adds', () => {
    const name = patients.columns.find((c) => c.name === 'full_name')!;
    expect(name).toMatchObject({ field: true, pii: true });
    expect(name.label?.en).toBe('Name');
    expect(patients.columns.find((c) => c.name === 'id')!.field).toBe(false);
  });
  it('knows the relations in both directions', () => {
    expect(patients.outgoing).toEqual([
      { column: 'doctor', table: 'doctors', onDelete: 'SET NULL' },
    ]);
    expect(models.find((m) => m.name === 'doctors')!.incoming).toEqual([
      { table: 'patients', column: 'doctor' },
    ]);
  });
  it('lists the endpoints of the table only, and who may do what', () => {
    expect(patients.endpoints.map((e) => e.path)).toEqual([
      '/api/v1/patients',
      '/api/v1/patients/{id}',
    ]);
    expect(patients.access).toEqual([
      { role: 'reception', scope: 'team', actions: ['read', 'create'] },
    ]);
    expect(models.find((m) => m.name === 'doctors')!.access.map((a) => a.role)).toEqual(['nurse']);
  });
  it('platform tables with no entity carry no spec data', () => {
    const t = tableModels(
      parseTables(['CREATE TABLE "audit_log" ("id" uuid PRIMARY KEY);']),
      spec,
      endpoints,
      roles,
    );
    expect(t[0]).toMatchObject({ name: 'audit_log', entity: null, endpoints: [], access: [] });
  });
  it('without migrations the tables come from the spec alone', () => {
    const t = tableModels([], spec, endpoints, roles);
    expect(t.map((m) => m.name)).toEqual(['doctors', 'patients']);
    expect(t[1]!.outgoing).toEqual([{ column: 'doctor', table: 'Doctor', onDelete: null }]);
  });
  it('endpointsOf matches the table path and below, never a longer name', () => {
    expect(endpointsOf(endpoints, '/api/v1/', 'patients')).toHaveLength(2);
  });
});

describe('looksDestructive', () => {
  it('flags statements that destroy data, not comments', () => {
    expect(looksDestructive('ALTER TABLE a DROP COLUMN b;')).toBe(true);
    expect(looksDestructive('-- DROP TABLE x\nCREATE TABLE y (a int);')).toBe(false);
  });
});
