-- M01 S04: per-user notification preferences and admin-console access to global feature flags.
CREATE TABLE platform.notification_preferences (
  org_id uuid NOT NULL,
  user_id uuid NOT NULL,
  kind text NOT NULL,
  channel text NOT NULL CHECK (channel IN ('in_app','email')),
  enabled boolean NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, user_id, kind, channel)
);
ALTER TABLE platform.notification_preferences ENABLE ROW LEVEL SECURITY;
ALTER TABLE platform.notification_preferences FORCE ROW LEVEL SECURITY;
CREATE POLICY org_isolation ON platform.notification_preferences
  USING (org_id = nullif(current_setting('app.org_id', true), '')::uuid)
  WITH CHECK (org_id = nullif(current_setting('app.org_id', true), '')::uuid);
GRANT SELECT, INSERT, UPDATE, DELETE ON platform.notification_preferences TO nuzm_app, nuzm_worker;

-- Notifications are per recipient: a member must never read a colleague's notifications. app.user_id is set
-- together with app.org_id by Db.withOrg(..., { userId }) for the recipient-facing endpoints.
CREATE POLICY recipient_only ON platform.notifications AS RESTRICTIVE FOR SELECT TO nuzm_app
  USING (user_id = nullif(current_setting('app.user_id', true), '')::uuid);
-- (Producers insert notifications for other users WITHOUT `RETURNING`; the id is generated by the caller.)

-- Global flag writes from the admin console (previously break-glass only).
CREATE POLICY flags_platform ON platform.feature_flags FOR ALL TO nuzm_app
  USING (current_setting('app.platform_scope', true) = 'admin')
  WITH CHECK (current_setting('app.platform_scope', true) = 'admin');
