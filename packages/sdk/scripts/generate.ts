/**
 * Generates src/schema.ts (types for every path/operation) from spec/openapi/openapi.yaml.
 * `--check` regenerates in memory and fails if the committed file is stale (run in CI via `pnpm sdk:check`),
 * so the portals can never call an operation the contract does not declare.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';

const root = join(import.meta.dirname, '..', '..', '..');
const out = join(import.meta.dirname, '..', 'src', 'schema.ts');
const HEADER = '// GENERATED by `pnpm sdk:generate` from spec/openapi/openapi.yaml. DO NOT EDIT.\n';

const ast = await openapiTS(new URL(`file://${join(root, 'spec/openapi/openapi.yaml')}`), {
  defaultNonNullable: false, // request fields with a server-side default stay optional for callers
});
const next = HEADER + astToString(ast);

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(out, 'utf8');
  } catch {
    /* missing */
  }
  if (current !== next) {
    console.error(
      'packages/sdk/src/schema.ts is stale: run `pnpm sdk:generate` and commit the result',
    );
    process.exit(1);
  }
  console.log('sdk schema is up to date');
} else {
  writeFileSync(out, next);
  console.log(`wrote ${out}`);
}
